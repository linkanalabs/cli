// Release reads the tag out of the redirect rather than calling the REST API,
// which is capped at 60 requests/hour per IP.
func TestRelease(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		w.Header().Set("Location", "https://github.com/linkanalabs/cli/releases/tag/v0.8.1")
		w.WriteHeader(http.StatusFound)
	}))
	defer srv.Close()
	stubReleasesURL(t, srv.URL)

	got, err := Release(context.Background(), srv.Client())
	if err != nil {
		t.Fatalf("Release() error = %v", err)
	}
	if got != "v0.8.1" {
		t.Errorf("Release() = %q, want v0.8.1", got)
	}
}

// The redirect must not be followed: following it would fetch a full HTML page
// for no reason, and the tag is already in the header.
func TestReleaseDoesNotFollowRedirect(t *testing.T) {
	var hits int
	mux := http.NewServeMux()
	mux.HandleFunc("/releases/latest", func(w http.ResponseWriter, _ *http.Request) {
		hits++
		w.Header().Set("Location", "/releases/tag/v1.2.3")
		w.WriteHeader(http.StatusFound)
	})
	mux.HandleFunc("/releases/tag/", func(w http.ResponseWriter, _ *http.Request) {
		hits++
		_, _ = w.Write([]byte("<html>should not be fetched</html>"))
	})
	srv := httptest.NewServer(mux)
	defer srv.Close()
	stubReleasesURL(t, srv.URL+"/releases/latest")

	got, err := Release(context.Background(), srv.Client())
	if err != nil {
		t.Fatalf("Release() error = %v", err)
	}
	if got != "v1.2.3" {
		t.Errorf("Release() = %q, want v1.2.3", got)
	}
	if hits != 1 {
		t.Errorf("made %d requests, want exactly 1 (redirect was followed)", hits)
	}
}

// Setting CheckRedirect must not mutate the caller's client: doctor reuses one
// client for the backend reachability probe too.
func TestReleaseLeavesCallerClientAlone(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		w.Header().Set("Location", "/releases/tag/v1.0.0")
		w.WriteHeader(http.StatusFound)
	}))
	defer srv.Close()
	stubReleasesURL(t, srv.URL)

	hc := srv.Client()
	if _, err := Release(context.Background(), hc); err != nil {
		t.Fatalf("Release() error = %v", err)
	}
	if hc.CheckRedirect != nil {
		t.Error("Release mutated the caller's http.Client")
	}
}

