// realCask is the shape GoReleaser actually commits to the tap.
const realCask = `# This file was generated by GoReleaser. DO NOT EDIT.
cask "lk" do
  version "0.8.1"

  on_macos do
    on_arm do
      sha256 "22692f93c37033d8b9b5bf08611a6763ce6ec6718dee02f6a52d80479fadd296"
      url "https://github.com/linkanalabs/cli/releases/download/v#{version}/lk_#{version}_darwin_arm64.tar.gz"
    end
  end

  name "lk"
  homepage "https://github.com/linkanalabs/cli"
end
`

func stubTapURL(t *testing.T, url string) {
	t.Helper()
	prev := tapCaskURL
	tapCaskURL = url
	t.Cleanup(func() { tapCaskURL = prev })
}

func stubReleasesURL(t *testing.T, url string) {
	t.Helper()
	prev := releasesLatestURL
	releasesLatestURL = url
	t.Cleanup(func() { releasesLatestURL = prev })
}

func TestParseCaskVersion(t *testing.T) {
	cases := []struct {
		name string
		body string
		want string
	}{
		{"real cask", realCask, "0.8.1"},
		{"no indentation", "cask \"lk\" do\nversion \"1.0.0\"\n", "1.0.0"},
		{"prerelease", "  version \"1.0.0-rc.1\"\n", "1.0.0-rc.1"},
		{"first match wins", "  version \"1.0.0\"\n  version \"2.0.0\"\n", "1.0.0"},
		{"no version stanza", "cask \"lk\" do\nend\n", ""},
		{"version mentioned but not a stanza", "  url \"...v#{version}...\"\n", ""},
		{"empty", "", ""},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := parseCaskVersion([]byte(c.body)); got != c.want {
				t.Errorf("parseCaskVersion() = %q, want %q", got, c.want)
			}
		})
	}
}

func TestTapRemote(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		_, _ = w.Write([]byte(realCask))
	}))
	defer srv.Close()
	stubTapURL(t, srv.URL)

	got, err := TapRemote(context.Background(), srv.Client())
	if err != nil {
		t.Fatalf("TapRemote() error = %v", err)
	}
	if got != "0.8.1" {
		t.Errorf("TapRemote() = %q, want 0.8.1", got)
	}
}

// The tap request must never carry an Authorization header: this package is
// the one place lk talks to a host that is not the Linkana backend.
func TestTapRemoteSendsNoCredentials(t *testing.T) {
	var gotAuth string
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		gotAuth = r.Header.Get("Authorization")
		_, _ = w.Write([]byte(realCask))
	}))
	defer srv.Close()
	stubTapURL(t, srv.URL)

	if _, err := TapRemote(context.Background(), srv.Client()); err != nil {
		t.Fatalf("TapRemote() error = %v", err)
	}
	if gotAuth != "" {
		t.Errorf("Authorization header leaked to the tap host: %q", gotAuth)
	}
}

func TestTapRemoteErrors(t *testing.T) {
	t.Run("not found", func(t *testing.T) {
		srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
			w.WriteHeader(http.StatusNotFound)
		}))
		defer srv.Close()
		stubTapURL(t, srv.URL)

		if _, err := TapRemote(context.Background(), srv.Client()); err == nil {
			t.Fatal("expected an error on 404")
		}
	})

	t.Run("no version stanza", func(t *testing.T) {
		srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
			_, _ = w.Write([]byte("cask \"lk\" do\nend\n"))
		}))
		defer srv.Close()
		stubTapURL(t, srv.URL)

		if _, err := TapRemote(context.Background(), srv.Client()); err == nil {
			t.Fatal("expected an error when the cask carries no version")
		}
	})

	t.Run("unreachable", func(t *testing.T) {
		srv := httptest.NewServer(http.HandlerFunc(func(http.ResponseWriter, *http.Request) {}))
		url := srv.URL
		srv.Close() // nothing is listening now
		stubTapURL(t, url)

		if _, err := TapRemote(context.Background(), http.DefaultClient); err == nil {
			t.Fatal("expected an error when the host is unreachable")
		}
	})
}

